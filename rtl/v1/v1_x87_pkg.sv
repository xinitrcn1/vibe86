  // FRNDINT
  function automatic xres_t x87_rndint(input logic [79:0] a, input logic [15:0] fcw);
    xres_t r;
    fres_t f, t;
    if (x87_special_in(a, a, 1'b0, r)) return r;
    f = fp_round_int(a, FMT_F80, fcw[11:10], 1'b0, 1'b0);
    t = fp_round_int(a, FMT_F80, 2'd3, 1'b0, 1'b0);
    r.v = f.v;
    r.x = f.x;
    r.x[XDE] = x87_isdenorm(a);
    r.cc[1] = f.x[XPE] && f.v != t.v;
    return r;
  endfunction

  // FSCALE: a * 2^trunc(b)
  function automatic xres_t x87_scale(input logic [79:0] a, input logic [79:0] b,
                                      input logic [15:0] fcw);
    xres_t r;
    fres_t f, t;
    unpacked_t ua, ub;
    int n;
    if (x87_special_in(a, b, 1'b1, r)) return r;
    ua = unpack(a, FMT_F80, 1'b0);
    ub = unpack(b, FMT_F80, 1'b0);
    r.x[XDE] = ua.denorm || ub.denorm;
    if (ub.inf) begin
      // 0 * 2^+inf and inf * 2^-inf are invalid; otherwise inf or 0
      if ((ua.zero && !ub.sign) || (ua.inf && ub.sign)) begin
        r.v = X87_INDEF;
        r.x[XIE] = 1'b1;
      end else r.v = ub.sign ? {a[79], 79'b0} : {a[79], 15'h7FFF, 1'b1, 63'b0};
      return r;
    end
    if (ua.zero || ua.inf) begin
      r.v = a;
      return r;
    end
    if (ub.zero || ub.exp < 0) n = 0;
    else if (ub.exp > 20) n = ub.sign ? -(1 << 20) : (1 << 20);
    else begin
      n = int'(ub.sig >> (63 - int'(ub.exp)));
      if (ub.sign) n = -n;
    end
    f = round_pack(ua.sign, 20'(int'(ua.exp) + 64 + n), {64'b0, ua.sig}, 1'b0, FMT_F80,
                   fcw[11:10], 1'b0, 64);
    r.v = f.v;
    r.x = r.x | f.x;
    if (f.x[XPE]) begin
      t = round_pack(ua.sign, 20'(int'(ua.exp) + 64 + n), {64'b0, ua.sig}, 1'b0, FMT_F80,
                     2'd3, 1'b0, 64);
      r.cc[1] = f.v != t.v;
    end
    return r;
  endfunction

  // FXTRACT: exp = 1: the exponent as a value; exp = 0: the significand
  // (the exponent 0, the sign kept)
  function automatic xres_t x87_xtract(input logic [79:0] a, input logic exp);
    xres_t r;
    unpacked_t ua;
    if (x87_special_in(a, a, 1'b0, r)) return r;
    ua = unpack(a, FMT_F80, 1'b0);
    r.x[XDE] = ua.denorm;
    if (ua.zero) begin
      // the exponent of 0 is -infinity, with divide-by-zero
      r.x[XZE] = exp;
      r.v = exp ? {1'b1, 15'h7FFF, 1'b1, 63'b0} : a;
      return r;
    end
    if (ua.inf) begin
      r.v = exp ? {1'b0, 15'h7FFF, 1'b1, 63'b0} : a;
      return r;
    end
    if (exp) r.v = fp_from_int(64'(signed'(ua.exp)), 64, 1'b1, FMT_F80, 2'd0, 64).v;
    else r.v = {ua.sign, 15'h3FFF, ua.sig};
    return r;
  endfunction

  // FPREM (near = 0: the quotient truncated) / FPREM1 (near: IEEE remainder,
  // the quotient rounded to nearest even). Exact. A partial remainder when
  // the exponents differ by 64 or more: the dividend reduced by 2^(D-N)
  // times the divisor, N = 32 (SDM: "between 32 and 63"; chosen and checked
  // against the host), C2 = 1. cc: C0 = Q2, C3 = Q1, C1 = Q0, C2 incomplete.
  localparam int PREM_N = 32;
  function automatic xres_t x87_prem(input logic [79:0] a, input logic [79:0] b, input logic near);
    xres_t r;
    unpacked_t ua, ub;
    int d, s;
    logic [127:0] am, q, rem;
    logic sgn, partial;
    if (x87_special_in(a, b, 1'b1, r)) return r;
    ua = unpack(a, FMT_F80, 1'b0);
    ub = unpack(b, FMT_F80, 1'b0);
    r.x[XDE] = ua.denorm || ub.denorm;
    if (ua.inf || ub.zero) begin
      r.v = X87_INDEF;
      r.x[XIE] = 1'b1;
      return r;
    end
    if (ua.zero || ub.inf) begin
      r.v = a;
      return r;
    end
    d = int'(ua.exp) - int'(ub.exp);
    sgn = ua.sign;
    partial = d >= 64;
    q = '0;
    if (partial) begin
      am = {64'b0, ua.sig} << PREM_N;
      q = am / {64'b0, ub.sig};
      rem = am % {64'b0, ub.sig};
      s = int'(ua.exp) - PREM_N - 63;                  // rem's scale
    end else if (d >= 0) begin
      am = {64'b0, ua.sig} << d;
      q = am / {64'b0, ub.sig};
      rem = am % {64'b0, ub.sig};
      s = int'(ub.exp) - 63;
      if (near && ((rem << 1) > {64'b0, ub.sig} || ((rem << 1) == {64'b0, ub.sig} && q[0]))) begin
        q = q + 128'd1;
        rem = {64'b0, ub.sig} - rem;
        sgn = !sgn;
      end
    end else begin
      rem = {64'b0, ua.sig};
      s = int'(ua.exp) - 63;
      if (near && d == -1 && ua.sig > ub.sig) begin
        // |a| > |b|/2: the quotient rounds to 1
        q = 128'd1;
        rem = ({64'b0, ub.sig} << 1) - {64'b0, ua.sig};
        sgn = !sgn;
      end
    end
    if (rem == 0) r.v = {ua.sign, 79'b0};
    else r.v = round_pack(sgn, 20'(s + 127), rem, 1'b0, FMT_F80, 2'd0, 1'b0, 64).v;
    r.cc = {q[1], partial, q[0], q[2]};
    return r;
  endfunction

  // ---------------------------------------------------------------- wide arithmetic
  // a value m * 2^e, |m| < 2^256 (the transcendentals' intermediate form)
  typedef struct packed {
    logic               s;
    logic signed [19:0] e;
    logic [255:0]       m;
  } wf_t;

  function automatic wf_t wf_norm(input wf_t a);          // the leading 1 at bit 255
    wf_t r;
    int lz;
    r = a;
    if (a.m == 0) return r;
    lz = 0;
    for (int i = 0; i < 256; i++) if (a.m[255 - i] == 1'b0 && lz == i) lz = i + 1;
    r.m = a.m << lz;
    r.e = a.e - 20'(lz);
    return r;
  endfunction

  function automatic wf_t wf_of(input logic [79:0] v);     // an f80 (finite, non-zero)
    wf_t r;
    unpacked_t u;
    u = unpack(v, FMT_F80, 1'b0);
    r.s = u.sign;
    r.m = {192'b0, u.sig};
    r.e = 20'(int'(u.exp) - 63);
    return r;
  endfunction

  function automatic wf_t wf_q(input logic [127:0] q, input logic s);   // Q4.124
    wf_t r;
    r.s = s;
    r.m = {128'b0, q};
    r.e = -20'sd124;
    return r;
  endfunction

  // the value in Q4.124 (|value| < 16), truncated
  function automatic logic [127:0] wf_toq(input wf_t a);
    int sh;
    sh = int'(a.e) + 124;
    if (a.m == 0) return '0;
    if (sh >= 0) return 128'(a.m << sh);
    if (sh <= -256) return '0;
    return 128'(a.m >> (-sh));
  endfunction

  function automatic wf_t wf_mul(input wf_t a, input wf_t b);
    wf_t x, y, r;
    x = wf_norm(a);
    y = wf_norm(b);
    r.s = a.s ^ b.s;
    r.m = 256'(x.m[255:128]) * 256'(y.m[255:128]);
    r.e = x.e + y.e + 20'sd256;
    return r;
  endfunction

  function automatic wf_t wf_div(input wf_t a, input wf_t b);   // a / b, b != 0
    wf_t x, y, r;
    logic [383:0] num;
    x = wf_norm(a);
    y = wf_norm(b);
    // both significands in [2^127, 2^128): the quotient stays below 2^256
    num = {1'b0, x.m[255:128], 255'b0};
    r.s = a.s ^ b.s;
    r.m = 256'(num / 384'(y.m[255:128]));
    r.e = x.e + 20'sd128 - 20'sd255 - (y.e + 20'sd128);
    return r;
  endfunction

  function automatic wf_t wf_add(input wf_t a, input wf_t b);
    wf_t x, y, r;
    int d;
    if (a.m == 0) return b;
    if (b.m == 0) return a;
    x = wf_norm(a);
    y = wf_norm(b);
    x.m = x.m >> 2;                       // headroom for the carry
    x.e = x.e + 20'sd2;
    y.m = y.m >> 2;
    y.e = y.e + 20'sd2;
    if (y.e > x.e) begin
      wf_t t;
      t = x;
      x = y;
      y = t;
    end
    d = int'(x.e) - int'(y.e);
    y.m = (d > 255) ? 256'd0 : (y.m >> d);
    r.e = x.e;
    if (x.s == y.s) begin
      r.s = x.s;
      r.m = x.m + y.m;
    end else if (x.m >= y.m) begin
      r.s = x.s;
      r.m = x.m - y.m;
    end else begin
      r.s = y.s;
      r.m = y.m - x.m;
    end
    return r;
  endfunction

  // round to f80 (RC, 64 bits); C1 = rounded away from zero
  function automatic xres_t wf_round(input wf_t a, input logic [1:0] rm);
    xres_t r;
    fres_t f, t;
    wf_t n;
    r = '0;
    n = wf_norm(a);
    if (n.m == 0) begin
      r.v = {a.s, 79'b0};
      return r;
    end
    f = round_pack(n.s, n.e + 20'sd255, n.m[255:128], n.m[127:0] != 0, FMT_F80, rm, 1'b0, 64);
    t = round_pack(n.s, n.e + 20'sd255, n.m[255:128], n.m[127:0] != 0, FMT_F80, 2'd3, 1'b0, 64);
    r.v = f.v;
    r.x = f.x;
    r.cc[1] = f.x[XPE] && f.v != t.v;
    return r;
  endfunction

  // Q4.124 products and quotients (unsigned)
  function automatic logic [127:0] qmul(input logic [127:0] a, input logic [127:0] b);
    logic [255:0] p;
    p = 256'(a) * 256'(b);
    return p[251:124];
  endfunction
  function automatic logic [127:0] qdiv(input logic [127:0] a, input logic [127:0] b);
    logic [255:0] n;
    n = {4'b0, a, 124'b0};
    return 128'(n / 256'(b));
  endfunction
  function automatic logic [127:0] qsqrt(input logic [127:0] a);   // sqrt in Q4.124
    logic [255:0] rad;
    logic [127:0] x;
    logic rz;
    rad = {4'b0, a, 124'b0};
    x = isqrt256(rad, rz);
    return x;
  endfunction

  localparam logic [127:0] Q_ONE = 128'd1 << 124;

  // ---------------------------------------------------------------- transcendentals
  // 2^x - 1 for |x| < 2 (the SDM defines -1 <= x <= 1)
  function automatic wf_t tr_f2xm1(input logic [79:0] x);
    wf_t y, tw;
    logic [127:0] yq, t;
    y = wf_mul(wf_of(x), wf_q(K_LN2, 1'b0));       // y = x ln 2
    yq = wf_toq(y);
    t = k_invfact(34);
    for (int k = 32; k >= 0; k--) begin
      logic [127:0] p;
      p = qmul(yq, t);
      t = y.s ? k_invfact(k + 1) - p : k_invfact(k + 1) + p;
    end
    tw = wf_q(t, 1'b0);
    return wf_mul(y, tw);
  endfunction

  // ln(1 + u) / ln 2 given z = u / (2 + u) (|z| < 0.18): 2 z S(z^2) / ln 2
  function automatic wf_t tr_log2_z(input wf_t z);
    logic [127:0] zq, z2, s;
    zq = wf_toq(z);
    z2 = qmul(zq, zq);
    s = k_invodd(30);
    for (int k = 29; k >= 0; k--) s = k_invodd(k) + qmul(z2, s);
    return wf_mul(wf_mul(z, wf_q(s << 1, 1'b0)), wf_q(K_LOG2E, 1'b0));
  endfunction

  // log2(x), x > 0 finite
  function automatic wf_t tr_log2(input logic [79:0] x);
    unpacked_t u;
    wf_t num, den, l, ew;
    int e;
    logic [255:0] n;
    u = unpack(x, FMT_F80, 1'b0);
    e = int'(u.exp);
    // m in [1/sqrt2, sqrt2): u = m - 1 at scale 2^-64
    if (u.sig > 64'hB504_F333_F9DE_6484) begin
      // m = sig/2^64 in (sqrt2/2, 1): m - 1 < 0
      e = e + 1;
      num.s = 1'b1;
      num.m = 256'(65'h1_0000_0000_0000_0000) - 256'(u.sig);
      num.e = -20'sd64;
      den.s = 1'b0;
      den.m = 256'(66'h2_0000_0000_0000_0000) + 256'(u.sig) - 256'(65'h1_0000_0000_0000_0000);
      den.e = -20'sd64;
    end else begin
      num.s = 1'b0;
      num.m = 256'(u.sig) - 256'(64'h8000_0000_0000_0000);
      num.e = -20'sd63;
      den.s = 1'b0;
      den.m = 256'(65'h1_0000_0000_0000_0000) + 256'(u.sig) - 256'(64'h8000_0000_0000_0000);
      den.e = -20'sd63;
    end
    if (num.m == 0) l = '0;
    else l = tr_log2_z(wf_div(num, den));
    if (e == 0) return l;
    n = (e < 0) ? 256'(-e) : 256'(e);
    ew.s = e < 0;
    ew.m = n;
    ew.e = 20'sd0;
    return wf_add(ew, l);
  endfunction

  // log2(1 + x) for x > -1, finite
  function automatic wf_t tr_log2p1(input logic [79:0] x);
    wf_t xw, den;
    xw = wf_of(x);
    // 2 + x in Q4.124 (x > -1: positive)
    den = wf_q(xw.s ? (Q_ONE << 1) - wf_toq(xw) : (Q_ONE << 1) + wf_toq(xw), 1'b0);
    return tr_log2_z(wf_div(xw, den));
  endfunction

  // atan(a), 0 <= a <= 1 (wide)
  function automatic wf_t tr_atan01(input wf_t a);
    logic [127:0] aq, b2, s;
    wf_t n;
    n = wf_norm(a);
    if (n.m == 0 || int'(n.e) + 256 < -40) return a;  // atan(a) = a(1 - a^2/3...): below an ulp
    aq = wf_toq(a);
    for (int i = 0; i < 3; i++) aq = qdiv(aq, Q_ONE + qsqrt(Q_ONE + qmul(aq, aq)));
    b2 = qmul(aq, aq);
    s = k_invodd(24);
    for (int k = 23; k >= 0; k--) s = k_invodd(k) - qmul(b2, s);
    return wf_q(qmul(aq, s) << 3, 1'b0);
  endfunction

  // sin/cos of t in [0, pi/4 + a little] (wide), t >= 0
  function automatic wf_t tr_sin(input wf_t t);
    logic [127:0] tq, t2, s;
    tq = wf_toq(t);
    t2 = qmul(tq, tq);
    s = k_invfact(33);
    for (int k = 15; k >= 0; k--) s = k_invfact(2 * k + 1) - qmul(t2, s);
    return wf_mul(t, wf_q(s, 1'b0));
  endfunction
  function automatic wf_t tr_cos(input wf_t t);
    logic [127:0] tq, t2, c;
    tq = wf_toq(t);
    t2 = qmul(tq, tq);
    c = k_invfact(32);
    for (int k = 15; k >= 0; k--) c = k_invfact(2 * k) - qmul(t2, c);
    return wf_q(c, 1'b0);
  endfunction

  // op: 0 F2XM1(a), 1 FYL2X (b log2 a), 2 FYL2XP1 (b log2(a + 1)),
  // 3 FPATAN (atan(b / a): b = ST(1), a = ST(0)), 4 FSIN, 5 FCOS, 6 FPTAN
  // (tangent). cc C2 = 1 (and nowr): FSIN/FCOS/FPTAN out of range (|a| >= 2^63)
  function automatic xres_t x87_trans(input logic [2:0] op, input logic [79:0] a,
                                      input logic [79:0] b, input logic [15:0] fcw);
    xres_t r;
    logic [1:0] rm;
    logic two;
    unpacked_t ua, ub;
    rm = fcw[11:10];
    two = op == 3'd1 || op == 3'd2 || op == 3'd3;
    if (x87_special_in(a, b, two, r)) return r;
    ua = unpack(a, FMT_F80, 1'b0);
    ub = unpack(b, FMT_F80, 1'b0);
    r.x[XDE] = ua.denorm || (two && ub.denorm);
    case (op)
      3'd0: begin                                        // F2XM1
        if (ua.zero) r.v = a;
        else if (ua.inf) r.v = ua.sign ? {1'b1, 15'h3FFF, 1'b1, 63'b0} : a;
        else if (ua.exp >= 1) begin
          r.v = X87_INDEF;                               // outside the domain
          r.x[XIE] = 1'b1;
        end else begin
          logic [5:0] dx;
          dx = r.x;
          r = wf_round(tr_f2xm1(a), rm);
          r.x = r.x | dx;
        end
      end
      3'd1, 3'd2: begin                                  // FYL2X, FYL2XP1
        logic below, neg_one, zero_arg;
        below = (op == 3'd1) ? (ua.sign && !ua.zero)
                             : (ua.sign && (ua.exp > 0 || (ua.exp == 0 && ua.sig > 64'h8000_0000_0000_0000)));
        neg_one = op == 3'd2 && ua.sign && ua.exp == 0 && ua.sig == 64'h8000_0000_0000_0000;
        zero_arg = (op == 3'd1) ? ua.zero : neg_one;      // log of 0
        if (below || (ua.inf && ua.sign)) begin
          r.v = X87_INDEF;
          r.x[XIE] = 1'b1;
        end else if (zero_arg) begin
          if (ub.zero) begin
            r.v = X87_INDEF;
            r.x[XIE] = 1'b1;
          end else begin
            r.v = {!ub.sign, 15'h7FFF, 1'b1, 63'b0};     // -inf times y
            r.x[XZE] = !ub.inf;
          end
        end else if (ua.inf) begin
          if (ub.zero) begin
            r.v = X87_INDEF;
            r.x[XIE] = 1'b1;
          end else r.v = {ub.sign, 15'h7FFF, 1'b1, 63'b0};
        end else begin
          wf_t l;
          l = (op == 3'd1) ? tr_log2(a) : (ua.zero ? '0 : tr_log2p1(a));
          if (op == 3'd2 && ua.zero) l.s = ua.sign;
          if (ub.inf) begin
            if (l.m == 0) begin
              r.v = X87_INDEF;
              r.x[XIE] = 1'b1;
            end else r.v = {l.s ^ ub.sign, 15'h7FFF, 1'b1, 63'b0};
          end else if (ub.zero || l.m == 0) r.v = {l.s ^ ub.sign, 79'b0};
          else begin
            logic [5:0] dx;
            dx = r.x;
            r = wf_round(wf_mul(wf_of(b), l), rm);
            r.x = r.x | dx;
          end
        end
      end
      3'd3: begin                                        // FPATAN: atan2(b, a)
        wf_t at, th;
        logic swap;
        if (ub.zero) begin
          // y = 0: +0 / +finite / +inf -> 0; -0 / -finite / -inf -> pi
          if (ua.sign) r = wf_round(wf_q(K_PI, ub.sign), rm);
          else r.v = b;
        end else if (ub.inf || ua.zero || ua.inf) begin
          logic [127:0] k;
          if (ub.inf && ua.inf) k = ua.sign ? K_PI2 + K_PI4 : K_PI4;
          else if (ub.inf || ua.zero) k = K_PI2;
          else k = ua.sign ? K_PI : 128'd0;
          if (k == 0) r.v = {ub.sign, 79'b0};
          else r = wf_round(wf_q(k, ub.sign), rm);
        end else begin
          wf_t ax, ay;
          logic [5:0] dx;
          dx = r.x;
          ax = wf_of(a);
          ay = wf_of(b);
          ax.s = 1'b0;
          ay.s = 1'b0;
          swap = {ub.exp, ub.sig} > {ua.exp, ua.sig};
          at = tr_atan01(swap ? wf_div(ax, ay) : wf_div(ay, ax));
          th = at;
          if (swap) th = wf_add(wf_q(K_PI2, 1'b0), '{s: 1'b1, e: at.e, m: at.m});
          if (ua.sign) th = wf_add(wf_q(K_PI, 1'b0), '{s: 1'b1, e: th.e, m: th.m});
          th.s = ub.sign;
          r = wf_round(th, rm);
          r.x = r.x | dx;
        end
      end
      default: begin                                     // FSIN, FCOS, FPTAN
        if (ua.inf) begin
          r.v = X87_INDEF;
          r.x[XIE] = 1'b1;
        end else if (!ua.zero && ua.exp >= 63) begin
          r.cc[2] = 1'b1;                                // out of range: unchanged
          r.nowr = 1'b1;
        end else if (ua.zero) r.v = (op == 3'd5) ? X87_ONE : a;
        else begin
          wf_t t, s, c, rs, rc;
          logic [1:0] j;
          logic sw;
          logic [5:0] dx;
          dx = r.x;
          if (ua.exp < -1) begin
            t = wf_of(a);
            t.s = 1'b0;
            j = 2'd0;
            sw = 1'b0;
          end else begin
            // |a| = sig * 2^(exp - 63) = X * 2^-65; pi/2 = K_PI66 * 2^-65
            logic [255:0] xx, qq, rr;
            xx = 256'(ua.sig) << (int'(ua.exp) + 2);
            qq = xx / 256'(K_PI66);
            rr = xx % 256'(K_PI66);
            j = qq[1:0];
            sw = (rr << 1) > 256'(K_PI66);
            t.s = 1'b0;
            t.m = sw ? 256'(K_PI66) - rr : rr;
            t.e = -20'sd65;
          end
          s = (t.m == 0) ? '0 : tr_sin(t);
          c = tr_cos(t);
          if (sw) begin
            wf_t tmp;
            tmp = s;
            s = c;
            c = tmp;
          end
          case (j)
            2'd0: begin rs = s; rc = c; end
            2'd1: begin rs = c; rc = s; rc.s = !rc.s; end
            2'd2: begin rs = s; rs.s = !rs.s; rc = c; rc.s = !rc.s; end
            default: begin rs = c; rs.s = !rs.s; rc = s; end
          endcase
          if (ua.sign) rs.s = !rs.s;
          if (op == 3'd4) r = wf_round(rs, rm);
          else if (op == 3'd5) r = wf_round(rc, rm);
          else r = wf_round(wf_div(rs, rc), rm);
          r.x = r.x | dx;
        end
      end
    endcase
    return r;
  endfunction

