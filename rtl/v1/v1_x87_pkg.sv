// v1_x87_pkg: the x87 floating-point unit of the v1 core (D-016).
//
// The x87's arithmetic on top of the shared datapath (v1_fp_pkg, D-009):
// loads and stores of every x87 memory format (f32, f64, f80, 16/32/64-bit
// integers, 18-digit packed BCD), the arithmetic with FCW's precision and
// rounding control, comparisons and FXAM, FPREM/FPREM1 (exact, in wide
// integers), FSCALE, FXTRACT, FRNDINT, and the transcendental instructions.
// Rules from the Intel SDM Vol. 1: 8.1.3 (condition codes), 8.2 (data
// types, the "unsupported" encodings of 8.2.2), 8.3.10 (pi), 8.5 (the
// exceptions, masked responses), 4.8.3.5 / Table 4-7 (NaN operands), and
// the instruction pages of Vol. 2 (results for special operands).
//
// Transcendentals (FSIN, FCOS, FPTAN, FPATAN, F2XM1, FYL2X, FYL2XP1) are
// evaluated in fixed point with 124 fraction bits ("Q4.124") or a wide
// floating form (a 256-bit significand), then rounded once to the 64-bit
// x87 significand with FCW.RC:
//   F2XM1   2^x - 1 = y * sum y^k/(k+1)!, y = x ln 2 (Horner);
//   FYL2X   log2 m' = 2 atanh(z) / ln 2, z = (m'-1)/(m'+1), m' in [1/sqrt2,
//           sqrt2) (the atanh series: z^2 <= 0.0295);
//   FYL2XP1 the same with z = x/(2+x), exact relative accuracy near 0;
//   FPATAN  three argument halvings atan(a) = 2 atan(a / (1 + sqrt(1 +
//           a^2))) to |a| < 0.1, then the atan series; the octant by the
//           signs and magnitudes (atan2's conventions, the FPATAN table);
//   FSIN/FCOS/FPTAN  exact reduction modulo pi/2 with the x87's 66-bit pi
//           (SDM Vol. 1 8.3.10), so results near multiples of pi agree with
//           Intel's; to [0, pi/4] by complement; the sine and cosine series.
// The series are those of J.-M. Muller, *Elementary Functions: Algorithms
// and Implementation*, 3rd ed., Birkhauser 2016 (ch. 2 polynomial
// evaluation, ch. 11 range reduction); with ~120 bits before the final
// rounding the results are correctly rounded except in rare hard cases, and
// within the SDM's "1 ulp" claims (tests: rtl/v1/tb/tb_x87_ref against the
// host's x87). This is a behavioural reference for v1: a later core
// evaluates it iteratively (docs/synthesis.md).
