  // The functions below take whole x87 words and unpacked or wide values
  // and read the fields each case needs (sign, exponent, class bits...).
  /* verilator lint_off UNUSEDSIGNAL */

  // results: the value, the exception flags (IE DE ZE OE UE PE), the
  // condition codes {C3, C2, C1, C0} the operation defines (C1: rounded up
  // for arithmetic), and nowr: no result (FSIN... out of range)
  typedef struct packed {
    logic [79:0] v;
    logic [5:0]  x;
    logic [3:0]  cc;
    logic        nowr;
  } xres_t;

  localparam logic [79:0] X87_INDEF = {1'b1, 15'h7FFF, 2'b11, 62'b0};
  localparam logic [79:0] X87_ONE = {1'b0, 15'h3FFF, 1'b1, 63'b0};

  // the tag of a value (FTW: 00 valid, 01 zero, 10 special; 11 is empty)
  function automatic logic [1:0] x87_tag(input logic [79:0] v);
    if (v[78:64] == 15'h0 && v[63:0] == 64'h0) return 2'b01;
    if (v[78:64] == 15'h7FFF || v[78:64] == 15'h0 || !v[63]) return 2'b10;
    return 2'b00;
  endfunction

  // the encodings the 80387 and later reject (SDM Vol. 1 8.2.2): a non-zero
  // exponent with the integer bit clear (unnormals, pseudo-NaNs and
  // pseudo-infinities)
  function automatic logic x87_unsup(input logic [79:0] v);
    return v[78:64] != 15'h0 && !v[63];
  endfunction
  function automatic logic x87_isnan(input logic [79:0] v);
    return v[78:64] == 15'h7FFF && v[63] && v[62:0] != 63'h0;
  endfunction
  function automatic logic x87_issnan(input logic [79:0] v);
    return x87_isnan(v) && !v[62];
  endfunction
  function automatic logic x87_isinf(input logic [79:0] v);
    return v[78:64] == 15'h7FFF && v[63:0] == 64'h8000_0000_0000_0000;
  endfunction
  function automatic logic x87_iszero(input logic [79:0] v);
    return v[78:0] == 79'h0;
  endfunction
  function automatic logic x87_isdenorm(input logic [79:0] v);
    return v[78:64] == 15'h0 && v[63:0] != 64'h0;
  endfunction

  // the NaN an operation returns (SDM Vol. 1 Table 4-7, x87 column): one
  // NaN quieted; two: a QNaN over an SNaN, else the larger significand
  function automatic logic [79:0] x87_nanres(input logic [79:0] a, input logic [79:0] b,
                                             input logic two);
    logic an, bn;
    logic [79:0] qa, qb;
    an = x87_isnan(a);
    bn = two && x87_isnan(b);
    qa = a | (80'd1 << 62);
    qb = b | (80'd1 << 62);
    if (an && bn) begin
      if (x87_issnan(a) != x87_issnan(b)) return x87_issnan(a) ? qb : qa;
      return (b[62:0] > a[62:0]) ? qb : qa;
    end
    return an ? qa : qb;
  endfunction

  // NaN or unsupported operands: 1 and the result (IE for SNaN/unsupported)
  function automatic logic x87_special_in(input logic [79:0] a, input logic [79:0] b,
                                          input logic two, output xres_t r);
    r = '0;
    if (x87_unsup(a) || (two && x87_unsup(b))) begin
      r.v = X87_INDEF;
      r.x[XIE] = 1'b1;
      return 1'b1;
    end
    if (x87_isnan(a) || (two && x87_isnan(b))) begin
      r.x[XIE] = x87_issnan(a) || (two && x87_issnan(b));
      r.v = x87_nanres(a, b, two);
      return 1'b1;
    end
    return 1'b0;
  endfunction

  // FCW: precision control (00 24 bits, 10 53, 11 64; 01 reserved: 64) and
  // rounding control
  function automatic int x87_prec(input logic [1:0] pc);
    case (pc)
      2'b00: return 24;
      2'b10: return 53;
      default: return 64;
    endcase
  endfunction

  // ---------------------------------------------------------------- arithmetic
  // op: 0 add, 1 sub (a - b), 2 mul, 3 div (a / b), 4 sqrt(a); PC and RC apply
  function automatic xres_t x87_arith(input logic [2:0] op, input logic [79:0] a,
                                      input logic [79:0] b, input logic [15:0] fcw);
    xres_t r;
    fres_t f, t;
    if (x87_special_in(a, b, op != 3'd4, r)) return r;
    f = fp_arith_raw({1'b0, op}, a, b, 80'd0, FMT_F80, fcw[11:10], 1'b0, 1'b0, x87_prec(fcw[9:8]), 2'b00);
    r.v = f.v;
    r.x = f.x;
    if (f.x[XZE]) r.x[XDE] = 1'b0;          // a zero divisor hides a denormal dividend (as hardware)
    if (f.x[XPE]) begin
      t = fp_arith_raw({1'b0, op}, a, b, 80'd0, FMT_F80, 2'd3, 1'b0, 1'b0, x87_prec(fcw[9:8]), 2'b00);
      r.cc[1] = f.v != t.v;                  // C1: rounded away from zero
    end
    return r;
  endfunction

  // ---------------------------------------------------------------- loads
  // fmt: 0 f32, 1 f64, 2 f80, 3 i16, 4 i32, 5 i64, 6 packed BCD, 7 a constant
  // (lo[2:0]: FLD1 FLDL2T FLDL2E FLDPI FLDLG2 FLDLN2 FLDZ, rounded per RC)
  function automatic xres_t x87_load(input logic [2:0] fmt, input logic [63:0] lo,
                                     input logic [15:0] hi, input logic [15:0] fcw);
    xres_t r;
    fres_t f;
    r = '0;
    case (fmt)
      3'd0, 3'd1: begin
        // exact; SNaN: IE and quieted; a denormal source: DE
        f = fp_convert(fmt == 3'd0 ? {48'b0, lo[31:0]} : {16'b0, lo},
                       fmt == 3'd0 ? FMT_F32 : FMT_F64, FMT_F80, 2'd0, 1'b0, 1'b0, 64);
        r.v = f.v;
        r.x = f.x;
      end
      3'd2: r.v = {hi, lo};
      3'd3, 3'd4, 3'd5: begin
        f = fp_from_int(fmt == 3'd3 ? {{48{lo[15]}}, lo[15:0]} : fmt == 3'd4 ? {{32{lo[31]}}, lo[31:0]} : lo,
                        64, 1'b1, FMT_F80, 2'd0, 64);
        r.v = f.v;
      end
      3'd6: begin
        // 18 BCD digits (lo, hi[7:0]), the sign in hi[15] (SDM Vol. 1 4.7)
        logic [63:0] n;
        n = 64'd0;
        for (int i = 17; i >= 0; i--) begin
          logic [3:0] d;
          d = (i >= 16) ? hi[4 * (i - 16) +: 4] : lo[4 * i +: 4];
          n = n * 64'd10 + 64'(d);
        end
        f = fp_from_int(n, 64, 1'b0, FMT_F80, 2'd0, 64);
        r.v = {hi[15], f.v[78:0]};
      end
      default: r.v = k_fldconst(lo[2:0], fcw[11:10]);
    endcase
    return r;
  endfunction

  // ---------------------------------------------------------------- stores
  // fmt as x87_load (0-6); RC, or truncation (FISTTP); part: the high 16
  // bits of an f80 or BCD image
  function automatic xres_t x87_store(input logic [2:0] fmt, input logic [79:0] a,
                                      input logic [15:0] fcw, input logic trunc, input logic part);
    xres_t r;
    fres_t f, t;
    logic [1:0] rm;
    rm = trunc ? 2'd3 : fcw[11:10];
    r = '0;
    case (fmt)
      3'd0, 3'd1: begin
        logic [3:0] to;
        to = fmt == 3'd0 ? FMT_F32 : FMT_F64;
        if (x87_unsup(a)) begin
          r.v = qnan_indef(to);
          r.x[XIE] = 1'b1;
        end else begin
          f = fp_convert(a, FMT_F80, to, rm, 1'b0, 1'b0, 64);
          r.v = f.v;
          r.x = f.x;
          if (f.x[XPE]) begin
            t = fp_convert(a, FMT_F80, to, 2'd3, 1'b0, 1'b0, 64);
            r.cc[1] = f.v != t.v;
          end
        end
      end
      3'd2: r.v = part ? {64'b0, a[79:64]} : {16'b0, a[63:0]};
      3'd3, 3'd4, 3'd5: begin
        int iw;
        iw = fmt == 3'd3 ? 16 : fmt == 3'd4 ? 32 : 64;
        if (x87_unsup(a)) begin
          r.v = 80'd1 << (iw - 1);               // the integer indefinite
          r.x[XIE] = 1'b1;
        end else begin
          f = fp_to_int(a, FMT_F80, iw, 1'b1, rm, 1'b0);
          r.v = f.v;
          r.x = f.x;
          if (f.x[XPE] && !f.x[XIE]) begin
            t = fp_to_int(a, FMT_F80, iw, 1'b1, 2'd3, 1'b0);
            r.cc[1] = f.v != t.v;
          end
        end
      end
      default: begin
        // packed BCD: an integer of at most 18 digits; else IE and the BCD
        // indefinite (sign 1, FFFFh and C0h in the top bytes)
        logic [63:0] n, m;
        logic [79:0] img;
        logic bad;
        f = fp_to_int(a, FMT_F80, 64, 1'b1, rm, 1'b0);
        n = f.v[63:0];
        m = n[63] ? 64'd0 - n : n;
        bad = x87_unsup(a) || f.x[XIE] || m > 64'd999_999_999_999_999_999;
        if (bad) begin
          img = 80'hFFFF_C000_0000_0000_0000;
          r.x[XIE] = 1'b1;
        end else begin
          img = {a[79], 7'b0, 72'b0};
          for (int i = 0; i < 18; i++) begin
            img[4 * i +: 4] = 4'(m % 64'd10);
            m = m / 64'd10;
          end
          r.x = f.x;
          if (f.x[XPE]) begin
            t = fp_to_int(a, FMT_F80, 64, 1'b1, 2'd3, 1'b0);
            r.cc[1] = f.v != t.v;
          end
        end
        r.v = part ? {64'b0, img[79:64]} : {16'b0, img[63:0]};
      end
    endcase
    return r;
  endfunction

  // ---------------------------------------------------------------- compare
  // FCOM (quiet = 0: IE for any NaN) / FUCOM (quiet: IE for SNaN only); cc
  // {C3, C2, C1, C0}: > 0000, < 0001, = 1000, unordered 1101
  function automatic xres_t x87_compare(input logic [79:0] a, input logic [79:0] b,
                                        input logic quiet);
    xres_t r;
    logic [5:0] xe, xl;
    logic eq, lt;
    r = '0;
    if (x87_unsup(a) || x87_unsup(b) || x87_isnan(a) || x87_isnan(b)) begin
      r.cc = 4'b1101;
      r.x[XIE] = x87_unsup(a) || x87_unsup(b) || x87_issnan(a) || x87_issnan(b) || !quiet;
      return r;
    end
    eq = fp_cmp(a, b, FMT_F80, 5'd0, 1'b0, xe);
    lt = fp_cmp(a, b, FMT_F80, 5'd17, 1'b0, xl);
    r.x[XDE] = xe[XDE] | xl[XDE];
    r.cc = eq ? 4'b1000 : lt ? 4'b0001 : 4'b0000;
    return r;
  endfunction

  // FXAM: {C3, C2, C1, C0}; C1 the sign; C3 C2 C0: unsupported 000, NaN 001,
  // normal 010, infinity 011, zero 100, empty 101, denormal 110
  function automatic logic [3:0] x87_xam(input logic [79:0] a, input logic empty);
    logic [2:0] k;
    if (empty) k = 3'b101;
    else if (x87_unsup(a)) k = 3'b000;
    else if (x87_isnan(a)) k = 3'b001;
    else if (x87_isinf(a)) k = 3'b011;
    else if (x87_iszero(a)) k = 3'b100;
    else if (x87_isdenorm(a)) k = 3'b110;
    else k = 3'b010;
    return {k[2], k[1], a[79], k[0]};
  endfunction

