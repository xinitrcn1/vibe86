#!/usr/bin/env python3
"""x87const: the constant tables of rtl/v1/v1_x87_pkg.sv, computed exactly.

    x87const.py            print the SystemVerilog localparams

Everything is computed with Python's integers (and Machin's formula for pi:
J. Machin, 1706; pi/4 = 4 atan(1/5) - atan(1/239)) at 400 bits, then
truncated (fixed point, Q4.124) or rounded to the four x87 rounding modes
(FLDPI... use FCW.RC, Intel SDM Vol. 1 8.3.10). The output is pasted into
v1_x87_pkg.sv between its "x87const" markers; re-run to check.
"""

from fractions import Fraction

P = 400          # bits of every exact computation
Q = 124          # fraction bits of the Q4.124 fixed point


def atan_inv(n):
    """atan(1/n) * 2^P (n > 1), by the Gregory series."""
    s, k, t = 0, 0, (1 << P) // n
    n2 = n * n
    while t:
        s += t // (2 * k + 1) if k % 2 == 0 else -(t // (2 * k + 1))
        t //= n2
        k += 1
    return s


PI = 4 * (4 * atan_inv(5) - atan_inv(239))          # pi * 2^P


def ln2():
    """ln 2 * 2^P = sum 1/(k 2^k)."""
    s, k = 0, 1
    while True:
        t = (1 << P) // (k << k)
        if not t:
            return s
        s += t
        k += 1


LN2 = ln2()


def ln10():
    # ln 10 = 3 ln 2 + ln(5/4) = 3 ln 2 + 2 atanh(1/9)
    s, k, t = 0, 0, (1 << P) // 9
    while t:
        s += t // (2 * k + 1)
        t //= 81
        k += 1
    return 3 * LN2 + 2 * s


LN10 = ln10()


def q(x):
    """a value * 2^P -> Q4.124 (truncated)"""
    return x >> (P - Q)


def f80(num, rm):
    """a positive value num/2^P -> (exponent field, 64-bit significand) rounded (rm 0 RN 1 RD 2 RU 3 RZ)."""
    e = num.bit_length() - 1 - P            # unbiased exponent
    sh = num.bit_length() - 64
    sig, rest = num >> sh, num & ((1 << sh) - 1)
    half = 1 << (sh - 1)
    up = {0: rest > half or (rest == half and sig & 1), 1: False, 2: rest != 0, 3: False}[rm]
    sig += up
    if sig >> 64:
        sig >>= 1
        e += 1
    return e + 16383, sig


def main():
    print("  // x87const: generated by tools/gen/x87const.py (exact; re-run to check)")
    print(f"  localparam logic [127:0] K_LN2   = 128'h{q(LN2):032X};   // ln 2, Q4.124")
    print(f"  localparam logic [127:0] K_LOG2E = 128'h{q((1 << (2 * P)) // LN2):032X};   // 1/ln 2")
    print(f"  localparam logic [127:0] K_PI    = 128'h{q(PI):032X};   // pi")
    print(f"  localparam logic [127:0] K_PI2   = 128'h{q(PI // 2):032X};   // pi/2")
    print(f"  localparam logic [127:0] K_PI4   = 128'h{q(PI // 4):032X};   // pi/4")
    # 1/k! and 1/(2k+1)
    print("  function automatic logic [127:0] k_invfact(input int k);   // 1/k!, Q4.124")
    print("    case (k)")
    f = 1
    for k in range(0, 35):
        if k:
            f *= k
        print(f"      {k}: return 128'h{(1 << Q) // f:032X};")
    print("      default: return '0;")
    print("    endcase")
    print("  endfunction")
    print("  function automatic logic [127:0] k_invodd(input int k);   // 1/(2k+1), Q4.124")
    print("    case (k)")
    for k in range(0, 40):
        print(f"      {k}: return 128'h{(1 << Q) // (2 * k + 1):032X};")
    print("      default: return '0;")
    print("    endcase")
    print("  endfunction")
    # FLD constants, rounded per RC: 0 one, 1 log2 10, 2 log2 e, 3 pi, 4 log10 2, 5 ln 2, 6 zero
    consts = [None, (LN10 << P) // LN2, (1 << (2 * P)) // LN2, PI, (LN2 << P) // LN10, LN2]
    print("  // FLD1/FLDL2T/FLDL2E/FLDPI/FLDLG2/FLDLN2/FLDZ, rounded per FCW.RC")
    print("  function automatic logic [79:0] k_fldconst(input logic [2:0] c, input logic [1:0] rm);")
    print("    case ({c, rm})")
    for c in range(7):
        for rm in range(4):
            if c == 0:
                v = (16383 << 64) | (1 << 63)
            elif c == 6:
                v = 0
            else:
                e, s = f80(consts[c], rm)
                v = (e << 64) | s
            print(f"      {{3'd{c}, 2'd{rm}}}: return 80'h{v:020X};")
    print("      default: return '0;")
    print("    endcase")
    print("  endfunction")
    # the 66-bit pi of the x87's argument reduction (Intel SDM Vol. 1 8.3.10,
    # "Pi": 0.C90FDAA22168C234C x 2^2, i.e. pi truncated to 66 significant
    # bits): floor(pi * 2^64); pi/2 is that integer at scale 2^-65
    pi66 = PI >> (P - 64)
    assert pi66 == 0xC90FDAA22168C234C >> 2, hex(pi66)
    print(f"  localparam logic [65:0] K_PI66 = 66'h{pi66:017X};   // floor(pi * 2^64), Intel SDM Vol. 1 8.3.10")

if __name__ == "__main__":
    main()
